#!/usr/bin/env bash
# Writes the CLI reference page from the help text of every `javo` command.
# Run from anywhere: site/scripts/cli-reference.sh (needs Go).
set -euo pipefail
root=$(cd "$(dirname "$0")/../.." && pwd)
out=$root/site/src/content/docs/reference/cli.md
bin=$(mktemp -d)/javo
trap 'rm -rf "$(dirname "$bin")"' EXIT
(cd "$root" && go build -o "$bin" ./cmd/javo)

subcommands() {
  "$bin" "$@" --help | awk '/^Available Commands:/{f=1;next} /^$/{f=0} f{print $1}' | grep -v -x -e help -e completion || true
}

page() {
  local name="javo${*:+ $*}"
  [ $# -eq 0 ] || printf '## %s\n\n```text\n%s\n```\n\n' "$name" "$("$bin" "$@" --help)"
  for s in $(subcommands "$@"); do page "$@" "$s"; done
}

{
  cat <<'HEAD'
---
title: CLI
description: Every javo command and flag, from the binary's own help.
sidebar:
  order: 1
---

<!-- Generated by site/scripts/cli-reference.sh from `javo --help`; do not edit by hand. -->

The `javo` binary in the image runs every component and the admin commands. Run the admin commands in the pod that holds the database: `deploy/javo` with SQLite, `deploy/javo-controller` with Postgres (add `--database-engine=postgres --database-dsn-file=/etc/javo-db/dsn`). The image has no shell, so call the binary directly:

```sh
kubectl -n javo-system exec deploy/javo -- /javo user add alice --password-file - > alice.password
```

Some commands (`netprobe`, `runner`, `source-check`, `storage prepare`, `storage probe-step`) are run by the platform's own pods, not by people.

```text
HEAD
  "$bin" --help
  printf '```\n\n'
  page
} > "$out"
echo "wrote $out"
